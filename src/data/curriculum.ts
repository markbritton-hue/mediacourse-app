export const WEEKS: Week[] = (() => {
  const weeks: Week[] = [];
  let weekCounter = 1;
  for (const unit of UNITS) {
    for (let i = 0; i < unit.weekCount; i++) {
      if (weekCounter > 36) break;
      weeks.push({
        number: weekCounter,
        unitNumber: unit.number,
        title: i === 0 ? unit.title : undefined,
      });
      weekCounter++;
    }
  }
  return weeks;
})();

